                "import cv2\n",
                "import numpy as np\n",
                "\n",
                "def detect_red_boxes_opencv(page_img_bgr, min_w=50, min_h=40, border_inward_trim=4):\n",
                "    \"\"\"HSV color segmentation and contour detection for flattened red boxes.\"\"\"\n",
                "    hsv = cv2.cvtColor(page_img_bgr, cv2.COLOR_BGR2HSV)\n",
                "    lower_red1 = np.array([0, 100, 100])\n",
                "    upper_red1 = np.array([10, 255, 255])\n",
                "    lower_red2 = np.array([165, 100, 100])\n",
                "    upper_red2 = np.array([180, 255, 255])\n",
                "    mask = cv2.bitwise_or(cv2.inRange(hsv, lower_red1, upper_red1), cv2.inRange(hsv, lower_red2, upper_red2))\n",
                "    \n",
                "    kernel = cv2.getStructuringElement(cv2.MORPH_RECT, (5, 5))\n",
                "    closed = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, kernel, iterations=2)\n",
                "    contours, _ = cv2.findContours(closed, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)\n",
                "    \n",
                "    H, W = page_img_bgr.shape[:2]\n",
                "    boxes = []\n",
                "    for cnt in contours:\n",
                "        x, y, w, h = cv2.boundingRect(cnt)\n",
                "        if w < min_w or h < min_h or w > (W * 0.95) or h > (H * 0.95):\n",
                "            continue\n",
                "        # Inward trim to exclude the red border itself\n",
                "        x1 = min(W, x + border_inward_trim)\n",
                "        y1 = min(H, y + border_inward_trim)\n",
                "        x2 = max(0, x + w - border_inward_trim)\n",
                "        y2 = max(0, y + h - border_inward_trim)\n",
                "        if (x2 - x1) >= 20 and (y2 - y1) >= 20:\n",
                "            boxes.append((x1, y1, x2, y2))\n",
                "    return boxes\n",
                "\n",
                "# Execute recovery and crop extraction\n",
